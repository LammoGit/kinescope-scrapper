-- Initial coordinator schema.
--
-- Every table uses a generated identity primary key. Nested job configuration
-- (worker list and per-job server configs) is stored as JSONB because it is a
-- snapshot of the configuration at job creation time, not a live relation.

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text        NOT NULL,
    email         text        NOT NULL UNIQUE,
    password_hash bytea       NOT NULL,
    password_salt bytea       NOT NULL,
    role          text        NOT NULL DEFAULT 'viewer'
                              CHECK (role IN ('viewer', 'operator', 'administrator')),
    avatar        text        NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE workers (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               text        NOT NULL,
    host               text        NOT NULL,
    ssh_port           integer     NOT NULL CHECK (ssh_port BETWEEN 0 AND 65535),
    ssh_user           text        NOT NULL,
    ssh_key            text        NOT NULL DEFAULT '',
    threads            integer     NOT NULL CHECK (threads > 0),
    storage_path       text        NOT NULL,
    min_free_space_gb  integer     NOT NULL CHECK (min_free_space_gb >= 0),
    status             text        NOT NULL DEFAULT 'off'
                                   CHECK (status IN ('idle', 'off', 'upgrading', 'working')),
    public_key         bytea       NOT NULL DEFAULT ''
);

CREATE TABLE jobs (
    id                           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                         text        NOT NULL,
    range_from                   bigint      NOT NULL CHECK (range_from >= 0),
    range_to                     bigint      NOT NULL CHECK (range_to >= range_from),
    request_timeout              integer     NOT NULL DEFAULT 0 CHECK (request_timeout >= 0),
    max_tries                    integer     NOT NULL DEFAULT 0 CHECK (max_tries >= 0),
    global_rate_limit_rps        integer     NOT NULL DEFAULT 0 CHECK (global_rate_limit_rps >= 0),
    stop_on_consecutive_missing  integer     NOT NULL DEFAULT 0 CHECK (stop_on_consecutive_missing >= 0),
    status                       text        NOT NULL DEFAULT 'created'
                                             CHECK (status IN ('created', 'validating', 'running', 'pausing',
                                                               'paused', 'stopping', 'stopped', 'completed', 'failed')),
    paused                       boolean     NOT NULL DEFAULT false,
    expiration                   timestamptz NOT NULL DEFAULT '0001-01-01 00:00:00+00',
    workers                      jsonb       NOT NULL DEFAULT '[]'::jsonb
                                             CHECK (jsonb_typeof(workers) = 'array'),
    servers                      jsonb       NOT NULL DEFAULT '[]'::jsonb
                                             CHECK (jsonb_typeof(servers) = 'array'),
    created_at                   timestamptz NOT NULL DEFAULT now(),
    updated_at                   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ranges (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id           bigint      NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    range_start      bigint      NOT NULL CHECK (range_start >= 0),
    range_end        bigint      NOT NULL CHECK (range_end >= range_start),
    next_id          bigint      NOT NULL CHECK (next_id >= range_start),
    status           text        NOT NULL DEFAULT 'created'
                                 CHECK (status IN ('created', 'validating', 'running', 'pausing',
                                                   'paused', 'stopping', 'stopped', 'completed', 'failed')),
    leased_by        bigint      NOT NULL DEFAULT 0,
    lease_expires_at timestamptz,
    attempt          integer     NOT NULL DEFAULT 0 CHECK (attempt >= 0),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ranges_job_start_idx ON ranges (job_id, range_start);
CREATE INDEX ranges_lease_idx ON ranges (status, lease_expires_at);
CREATE INDEX ranges_worker_idx ON ranges (leased_by) WHERE leased_by <> 0;

CREATE TABLE videos (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       bigint      NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    title        text        NOT NULL,
    source_url   text        NOT NULL,
    download_url text        NOT NULL,
    found_at     timestamptz NOT NULL,
    downloaded_at timestamptz NOT NULL,
    file_size    bigint      NOT NULL CHECK (file_size > 0),
    mime_type    text        NOT NULL,
    status       text        NOT NULL,
    bucket_name  text        NOT NULL DEFAULT '',
    object_key   text        NOT NULL DEFAULT '',
    checksum     text        NOT NULL DEFAULT '',
    server_name  text        NOT NULL DEFAULT '',
    local_path   text        NOT NULL DEFAULT ''
);

CREATE INDEX videos_job_idx ON videos (job_id);
CREATE INDEX videos_found_idx ON videos (found_at DESC);

CREATE TABLE events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    level       text        NOT NULL CHECK (level IN ('Error', 'Warning', 'Info', 'Debug')),
    component   text        NOT NULL,
    job_id      bigint      NOT NULL DEFAULT 0,
    worker_id   bigint      NOT NULL DEFAULT 0,
    range_id    bigint      NOT NULL DEFAULT 0,
    resource_id bigint      NOT NULL DEFAULT 0,
    operation   text        NOT NULL,
    result      text        NOT NULL,
    error_code  integer     NOT NULL DEFAULT 0,
    message     text        NOT NULL
);

CREATE INDEX events_job_idx ON events (job_id);
CREATE INDEX events_worker_idx ON events (worker_id);
CREATE INDEX events_time_idx ON events (occurred_at DESC);

CREATE TABLE telemetry (
    job_id                 bigint           NOT NULL,
    range_id               bigint           NOT NULL,
    worker_id              bigint           NOT NULL,
    cpu_load               double precision NOT NULL DEFAULT 0,
    memory_load            double precision NOT NULL DEFAULT 0,
    disk_load              double precision NOT NULL DEFAULT 0,
    network_load           double precision NOT NULL DEFAULT 0,
    free_space_bytes       bigint           NOT NULL DEFAULT 0,
    opened_files           integer          NOT NULL DEFAULT 0,
    active_connections     integer          NOT NULL DEFAULT 0,
    worker_uptime          double precision NOT NULL DEFAULT 0,
    identifiers_per_second double precision NOT NULL DEFAULT 0,
    requests               integer          NOT NULL DEFAULT 0,
    found_materials        integer          NOT NULL DEFAULT 0,
    active_downloads       integer          NOT NULL DEFAULT 0,
    bytes_per_second       bigint           NOT NULL DEFAULT 0,
    avg_check_speed        double precision NOT NULL DEFAULT 0,
    avg_download_speed     double precision NOT NULL DEFAULT 0,
    download_queue_size    integer          NOT NULL DEFAULT 0,
    repeated_attempts      integer          NOT NULL DEFAULT 0,
    final_errors           integer          NOT NULL DEFAULT 0,
    oldest_in_queue        integer          NOT NULL DEFAULT 0,
    updated_at             timestamptz      NOT NULL DEFAULT now(),
    PRIMARY KEY (job_id, range_id, worker_id)
);

CREATE INDEX telemetry_worker_idx ON telemetry (worker_id);
